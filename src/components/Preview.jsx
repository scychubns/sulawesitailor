export default function SkirtPreview({ design,measurements}) {
  console.log('d',design)
  const patternId = `motif-${useId().replace(/:/g, "")}`;

  const skirtPath = skirtTemplates[design.model]?.[design.length];

  const motifImage =
    design.motifType === "image" &&
    typeof design.motifImage === "string" &&
    design.motifImage.trim() !== ""
      ? design.motifImage
      : "";

  const fillValue = motifImage
    ? `url(#${patternId})`
    : design.color || "#ffffff";

  return (
    <svg
      className="shirt-svg"
      viewBox="0 0 400 430"
      role="img"
      aria-label="Visualisasi desain rok"
    >
      <defs>
        {motifImage && (
          <pattern
            id={patternId}
            patternUnits="userSpaceOnUse"
            width="45"
            height="45"
          >
            <image
              href={motifImage}
              x="0"
              y="0"
              width="45"
              height="45"
              preserveAspectRatio="xMidYMid slice"
            />
          </pattern>
        )}
      </defs>

      <g 
      // transform="translate(0 0) scale(1.6)"
      >
        <g
          className="component-outline"
          fill={fillValue}
          stroke="#333"
          strokeWidth="1"
        >
          {skirtPath}
        </g>

        <g
          className="pocket-outline"
          fill={design.color || "#ffffff"}
          stroke="#333"
          strokeWidth="1"
        >
          {pocketTemplates[design.pocket] ?? null}
        </g>
      </g>
    </svg>
  );
}

